def generate_spec(category, product_def, variant_idx):
    """Generate a specification string for a product."""
    specs = product_def["specs"]
    if isinstance(specs, list):
        return specs[variant_idx % len(specs)]
    return specs


def generate_volume(category, product_def, variant_idx):
    """Generate a volume/capacity string."""
    volumes = product_def["volumes"]
    return volumes[variant_idx % len(volumes)]


def generate_price(product_def):
    """Generate a price within the product's price range."""
    low, high = product_def["price_range"]
    # Use log-normal distribution for realistic pricing
    log_low = math.log(low)
    log_high = math.log(high)
    log_price = random.uniform(log_low, log_high)
    return round(math.exp(log_price), 2)


def format_price(price):
    """Format price as CSV-friendly string."""
    return f"${price:,.2f}"


def generate_discount():
    """Generate a discount percentage (often empty)."""
    if random.random() < 0.7:  # 70% have no discount
        return ""
    return f"{random.choice([5, 10, 15, 20, 25, 30])}"


def generate_max_rcf(product_def, variant_idx):
    """Generate Max RCF for centrifuge-type products."""
    if "rcf" in product_def:
        return product_def["rcf"][variant_idx % len(product_def["rcf"])]
    return ""


def generate_row(product_id, category, product_def, brand, variant_idx):
    """Generate a single product row."""
    specs = generate_spec(category, product_def, variant_idx)
    volume = generate_volume(category, product_def, variant_idx)
    price = generate_price(product_def)
    rcf = generate_max_rcf(product_def, variant_idx)

    # Determine boolean flags
    refrigerated = product_def.get("refrigerated", random.random() < 0.15)
    sterile = product_def.get("sterile", random.random() < 0.2)
    endotoxin_free = product_def.get("endotoxin_free", random.random() < 0.1)

    # Generate model SKU
    brand_prefix = brand[:3].upper().replace(" ", "")
    sku = f"{brand_prefix}-{product_id.split('-')[1]}"

    # Application and use case
    application = product_def["application"]
    use_case_options = APPLICATION_USECASE_MAP.get(application, [application])
    use_case = product_def.get("use_case", random.choice(use_case_options))

    # Generate compatible_with
    compatible = product_def.get("compatible_with", "Standard laboratory consumables")

    # Generate used_for
    used_for = product_def.get("used_for", use_case)

    # Generate requires
    requires = product_def.get("requires", "Standard laboratory handling")

    # Generate alternative_to
    alt_to = product_def.get("alternative_to", f"Other {product_def['name'].lower()} with matching specifications")

    # Generate limitations
    limitations = "Verify compatibility and stated operating limits before use"

    # Generate typical user question
    typical_q = product_def.get(
        "typical_question",
        f"I need {use_case.lower()}. Is this {product_def['name'].lower()} suitable and what specifications should I check?"
    )

    return {
        "Product_ID": product_id,
        "Category": category,
        "Product_Name": product_def["name"],
        "Brand": brand,
        "Model_SKU": sku,
        "Specifications": specs,
        "Volume_or_Capacity": volume,
        "Max_RCF_xg": rcf,
        "Refrigerated": "Yes" if refrigerated else "No",
        "Sterile": "Yes" if sterile else "No",
        "Endotoxin_Free": "Yes" if endotoxin_free else "No",
        "Application": application,
        "Use_Case": use_case,
        "Compatible_With": compatible,
        "Used_For": used_for,
        "Requires": requires,
        "Alternative_To": alt_to,
        "Limitations_Notes": limitations,
        "Typical_User_Question": typical_q,
        "Price_USD": format_price(price),
        "Verification_Status": "Synthetic / unverified",
        "Data_Provenance": "Synthetic training product",
        "Source_Reference": "",
        "URL": "",
        "Discount": generate_discount(),
        "Deteded?": "",
    }


def main():
    # Read existing 500 products
    existing_rows = []
    with open("test_data.csv", "r") as f:
        reader = csv.DictReader(f)
        for row in reader:
            existing_rows.append(row)

    print(f"Read {len(existing_rows)} existing products")

    # Generate new products starting from LC-0501
    new_rows = []
    target_total = 10000
    new_needed = target_total - len(existing_rows)

    # Flatten all product definitions
    all_products = []
    for cat_name, cat_data in CATEGORIES.items():
        for prod_def in cat_data["products"]:
            all_products.append((cat_name, prod_def))

    print(f"Total product types: {len(all_products)}")
    print(f"Generating {new_needed} new products...")

    for i in range(new_needed):
        product_num = len(existing_rows) + i + 1
        product_id = f"LC-{product_num:04d}"

        # Pick a random product type
        cat_name, prod_def = random.choice(all_products)

        # Pick a random brand
        brand = random.choice(BRANDS)

        # Pick a variant index for spec/volume variation
        variant_idx = random.randint(0, 100)

        row = generate_row(product_id, cat_name, prod_def, brand, variant_idx)
        new_rows.append(row)

    # Combine existing + new
    all_rows = existing_rows + new_rows

    # Write output
    fieldnames = [
        "Product_ID", "Category", "Product_Name", "Brand", "Model_SKU",
        "Specifications", "Volume_or_Capacity", "Max_RCF_xg",
        "Refrigerated", "Sterile", "Endotoxin_Free", "Application",
        "Use_Case", "Compatible_With", "Used_For", "Requires",
        "Alternative_To", "Limitations_Notes", "Typical_User_Question",
        "Price_USD", "Verification_Status", "Data_Provenance",
        "Source_Reference", "URL", "Discount", "Deteded?"
    ]

    output_file = "test_data_10_000.csv"
    with open(output_file, "w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(all_rows)

    print(f"Wrote {len(all_rows)} products to {output_file}")

    # Verify
    with open(output_file, "r") as f:
        count = sum(1 for line in f) - 1  # minus header
    print(f"Verification: {count} data rows in output file")


